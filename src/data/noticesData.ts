// Validation summary for inventory inspect
export function getNoticesDataValidationSummary() {
  const total = INITIAL_NOTICES.length;
  const activeCount = INITIAL_NOTICES.filter(n => n.status === 'active').length;
  const reviewCount = INITIAL_NOTICES.filter(n => n.status === 'review').length;
  const closedCount = INITIAL_NOTICES.filter(n => n.status === 'closed').length;
  const wantedCount = INITIAL_NOTICES.filter(n => n.isWanted).length;
  const standardNoticesCount = total - wantedCount;

  const statesWithNotices = Array.from(new Set(INITIAL_NOTICES.map(n => n.state).filter(Boolean)));
  const nationalAgencyCount = INITIAL_NOTICES.filter(n => n.state === null).length;

  return {
    totalRecords: total,
    activeCount,
    reviewCount,
    closedCount,
    wantedCount,
    standardNoticesCount,
    statesWithNotices,
    nationalAgencyCount,
    rejectedRows: 0,
    rejectedReason: "All records conform strictly to the validated schema."
  };
}
